CREATE TABLE IF NOT EXISTS public.rango_capacidad (
    id_rango        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion     VARCHAR(20) NOT NULL UNIQUE,
    orden           INT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.rango_trabajadores (
    id_rango_trab   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
