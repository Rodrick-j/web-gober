CREATE INDEX IF NOT EXISTS idx_ubi_municipio ON public.ubicacion (municipio);
CREATE INDEX IF NOT EXISTS idx_ubi_zona ON public.ubicacion (zona);

CREATE TABLE IF NOT EXISTS public.formacion (
    id_formacion    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(40) NOT NULL UNIQUE,
