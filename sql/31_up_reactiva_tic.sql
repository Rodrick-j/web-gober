-- Vista General 
CREATE OR REPLACE VIEW public.v_emprendedores AS
SELECT
    p.id_persona,
    p.dip,
    p.nombre_completo,
    p.celular,
    f.nombre AS formacion,
    ec.nombre AS estado_civil,
    p.num_hijos,
    e.id_empresa,
    e.nombre_empresa,
    e.nit,
    (e.nit IS NOT NULL AND e.nit <> '') AS tiene_nit,
    e.usa_banca_movil,
    r.nombre_rubro AS rubro,
    u.municipio,
    u.zona,
    e.fecha_registro
FROM public.persona p
JOIN public.emprendimiento_persona ep ON ep.id_persona = p.id_persona
JOIN public.empresa e ON e.id_empresa = ep.id_empresa
LEFT JOIN public.formacion f ON f.id_formacion = p.id_formacion
LEFT JOIN public.estado_civil ec ON ec.id_estado_civil = p.id_estado_civil
LEFT JOIN public.rubro r ON r.id_rubro = e.id_rubro
LEFT JOIN public.ubicacion u ON u.id_ubicacion = e.id_ubicacion
WHERE p.activo = TRUE AND e.activo = TRUE;

-- Vista Agrupada para Gráficos
CREATE OR REPLACE VIEW public.v_empresas_stats AS
SELECT
    r.nombre_rubro,
    u.municipio,
    COUNT(e.id_empresa) AS total_empresas,
    SUM(CASE WHEN e.usa_banca_movil THEN 1 ELSE 0 END) AS con_banca_movil,
    SUM(CASE WHEN (e.nit IS NOT NULL AND e.nit <> '') THEN 1 ELSE 0 END) AS con_nit
FROM public.empresa e
JOIN public.rubro r ON r.id_rubro = e.id_rubro
JOIN public.ubicacion u ON u.id_ubicacion = e.id_ubicacion
WHERE e.activo = TRUE
GROUP BY r.nombre_rubro, u.municipio;

