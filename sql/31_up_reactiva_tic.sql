    id_motivo               INT REFERENCES public.motivo_emprendimiento(id_motivo) ON UPDATE CASCADE ON DELETE SET NULL,
    id_rubro                INT REFERENCES public.rubro(id_rubro) ON UPDATE CASCADE ON DELETE SET NULL,
    id_ubicacion            INT REFERENCES public.ubicacion(id_ubicacion) ON UPDATE CASCADE ON DELETE SET NULL,
    observaciones           TEXT NULL,
    fecha_creacion          TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    fecha_actualizacion     TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    activo                  BOOLEAN DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS idx_empresa_nombre ON public.empresa (nombre_empresa);
CREATE INDEX IF NOT EXISTS idx_empresa_nit ON public.empresa (nit);
CREATE INDEX IF NOT EXISTS idx_empresa_rubro ON public.empresa (id_rubro);
