CREATE TABLE IF NOT EXISTS public.rubro (
    id_rubro        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rubro    VARCHAR(60) NOT NULL UNIQUE,
    descripcion     VARCHAR(200) NULL,
