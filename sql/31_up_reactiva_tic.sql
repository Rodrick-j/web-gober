-- PROCEDIMIENTOS ALMACENADOS (POSTGRESQL FUNCTIONS)
-- Se han modificado para recibir IDs directamente (Mejor Práctica)

CREATE OR REPLACE FUNCTION public.sp_registrar_persona_v2(
    p_dip VARCHAR(20),
    p_nombre VARCHAR(160),
    p_celular VARCHAR(25),
    p_id_formacion INT,
    p_id_estado_civil INT,
    p_num_hijos INT
)
RETURNS INT AS $$
DECLARE
    new_id INT;
BEGIN
    INSERT INTO public.persona (dip, nombre_completo, celular, id_formacion, id_estado_civil, num_hijos)
    VALUES (p_dip, p_nombre, p_celular, p_id_formacion, p_id_estado_civil, COALESCE(p_num_hijos, 0))
    RETURNING id_persona INTO new_id;
    
    RETURN new_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
