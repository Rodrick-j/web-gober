CREATE TABLE IF NOT EXISTS public.persona (
    id_persona          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dip                 VARCHAR(20) NULL UNIQUE,
    nombre_completo     VARCHAR(160) NOT NULL,
    celular             VARCHAR(25) NULL,
    celular_2           VARCHAR(25) NULL,
    id_formacion        INT REFERENCES public.formacion(id_formacion) ON UPDATE CASCADE ON DELETE SET NULL,
    id_estado_civil     INT REFERENCES public.estado_civil(id_estado_civil) ON UPDATE CASCADE ON DELETE SET NULL,
    num_hijos           INT DEFAULT 0,
    observaciones       TEXT NULL,
    fecha_registro      TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    fecha_actualizacion TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    activo              BOOLEAN DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS idx_persona_nombre ON public.persona (nombre_completo);
CREATE INDEX IF NOT EXISTS idx_persona_celular ON public.persona (celular);

-- Trigger para auto-actualizar fecha_actualizacion
CREATE TRIGGER handle_updated_at_persona
    BEFORE UPDATE ON public.persona
    FOR EACH ROW EXECUTE FUNCTION extensions.moddatetime (fecha_actualizacion);

CREATE TABLE IF NOT EXISTS public.empresa (
    id_empresa              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_empresa          VARCHAR(160) NOT NULL,
