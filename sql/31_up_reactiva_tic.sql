CREATE TABLE IF NOT EXISTS public.log_cambios (
    id_log          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_afectada  VARCHAR(60) NOT NULL,
    id_registro     INT NOT NULL,
    accion          VARCHAR(20) NOT NULL, -- INSERT, UPDATE, DELETE
    usuario_uid     UUID NULL, -- Integra con Supabase Auth
    fecha_evento    TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    estado_anterior JSONB NULL,
    estado_nuevo    JSONB NULL
);
CREATE INDEX IF NOT EXISTS idx_log_tabla ON public.log_cambios (tabla_afectada);

-- Funciones PL/pgSQL para triggers genéricos de auditoría
CREATE OR REPLACE FUNCTION audit_log_changes()
RETURNS TRIGGER AS $$
BEGIN
    IF (TG_OP = 'DELETE') THEN
        INSERT INTO public.log_cambios (tabla_afectada, id_registro, accion, usuario_uid, estado_anterior)
        VALUES (TG_TABLE_NAME, OLD.id_persona, 'DELETE', auth.uid(), row_to_json(OLD)::jsonb);
        RETURN OLD;
    ELSIF (TG_OP = 'UPDATE') THEN
        -- Extrae el ID (Asume que la PK se llama id_persona o id_empresa)
        -- Para evitar fallos genéricos, este script es específico.
        INSERT INTO public.log_cambios (tabla_afectada, id_registro, accion, usuario_uid, estado_anterior, estado_nuevo)
        VALUES (TG_TABLE_NAME, NEW.id_persona, 'UPDATE', auth.uid(), row_to_json(OLD)::jsonb, row_to_json(NEW)::jsonb);
        RETURN NEW;
    ELSIF (TG_OP = 'INSERT') THEN
        INSERT INTO public.log_cambios (tabla_afectada, id_registro, accion, usuario_uid, estado_nuevo)
        VALUES (TG_TABLE_NAME, NEW.id_persona, 'INSERT', auth.uid(), row_to_json(NEW)::jsonb);
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- En PostgreSQL, los triggers genéricos requieren cuidado con la Primary Key.
-- Solo aplicamos auditoría detallada a Persona y Empresa (simplificado para este ejemplo).

CREATE OR REPLACE FUNCTION audit_log_empresa()
RETURNS TRIGGER AS $$
BEGIN
    IF (TG_OP = 'UPDATE') THEN
        INSERT INTO public.log_cambios (tabla_afectada, id_registro, accion, usuario_uid, estado_anterior, estado_nuevo)
        VALUES (TG_TABLE_NAME, NEW.id_empresa, 'UPDATE', auth.uid(), row_to_json(OLD)::jsonb, row_to_json(NEW)::jsonb);
        RETURN NEW;
    ELSIF (TG_OP = 'INSERT') THEN
        INSERT INTO public.log_cambios (tabla_afectada, id_registro, accion, usuario_uid, estado_nuevo)
        VALUES (TG_TABLE_NAME, NEW.id_empresa, 'INSERT', auth.uid(), row_to_json(NEW)::jsonb);
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER trg_persona_audit
    AFTER INSERT OR UPDATE ON public.persona
    FOR EACH ROW EXECUTE FUNCTION audit_log_changes();

CREATE TRIGGER trg_empresa_audit
    AFTER INSERT OR UPDATE ON public.empresa
    FOR EACH ROW EXECUTE FUNCTION audit_log_empresa();


